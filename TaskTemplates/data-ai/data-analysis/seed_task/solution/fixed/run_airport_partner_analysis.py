def load_reference_metrics() -> types.ModuleType:
    module = types.ModuleType("embedded_reference_metrics")
    source = zlib.decompress(base64.b64decode(REFERENCE_METRICS_BLOB.encode("ascii"))).decode("utf-8")
    exec(compile(source, "embedded_reference_metrics.py", "exec"), module.__dict__)
    return module


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    data_root = Path(args.data)
    output_root = Path(args.output)
    output_root.mkdir(parents=True, exist_ok=True)

    ref = load_reference_metrics()
    bundle = ref.expected_bundle(data_root)

    bundle["source_inventory"].to_csv(output_root / "source_inventory.tsv", sep="\t", index=False)
    bundle["quality_checks"].to_csv(output_root / "quality_checks.tsv", sep="\t", index=False)
    bundle["period_summary"].to_csv(output_root / "airport_partner_zone_period_summary.csv", index=False)
    bundle["weather_sensitivity"].to_csv(
        output_root / "airport_weather_sensitivity.tsv", sep="\t", index=False
    )
    bundle["rankings"].to_csv(output_root / "airport_partner_zone_rankings.tsv", sep="\t", index=False)
    (output_root / "analysis_brief.md").write_text(bundle["analysis_brief"], encoding="utf-8")
    (output_root / "query_pack.sql").write_text(bundle["query_pack"], encoding="utf-8")


if __name__ == "__main__":
    main()
